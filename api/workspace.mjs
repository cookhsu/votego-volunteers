import {Pool} from 'pg';
import {randomBytes,createHash,scrypt,timingSafeEqual} from 'node:crypto';
import {promisify} from 'node:util';

const derive=promisify(scrypt);
const dbUrl=process.env.DATABASE_URL || process.env.POSTGRES_URL || process.env.STORAGE_URL;
const pool=dbUrl?new Pool({connectionString:dbUrl,max:3,connectionTimeoutMillis:6000,idleTimeoutMillis:12000}):null;
const teams=['活動組','後勤組','行政組','機動組'];
const sha=value=>createHash('sha256').update(value).digest('hex');
const equal=(a,b)=>timingSafeEqual(Buffer.from(sha(a),'hex'),Buffer.from(sha(b),'hex'));
const schema=`
CREATE TABLE IF NOT EXISTS users(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT UNIQUE NOT NULL, name TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('admin','coordinator','volunteer')), salt TEXT NOT NULL, password_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS volunteers(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INT UNIQUE REFERENCES users(id), name TEXT NOT NULL, team TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')));
CREATE TABLE IF NOT EXISTS events(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, place TEXT NOT NULL, starts TEXT NOT NULL, ends TEXT NOT NULL, CHECK(starts<ends));
CREATE TABLE IF NOT EXISTS shifts(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id INT NOT NULL REFERENCES events(id), volunteer_id INT NOT NULL REFERENCES volunteers(id), UNIQUE(event_id,volunteer_id));
CREATE TABLE IF NOT EXISTS tasks(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, due TEXT NOT NULL, done INT NOT NULL DEFAULT 0 CHECK(done IN (0,1)));
CREATE TABLE IF NOT EXISTS supplies(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT UNIQUE NOT NULL, quantity INT NOT NULL CHECK(quantity>=0));
CREATE TABLE IF NOT EXISTS audit(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id INT NOT NULL REFERENCES users(id), action TEXT NOT NULL, entity_id INT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW());
CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY, user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires_at TIMESTAMPTZ NOT NULL);
CREATE TABLE IF NOT EXISTS attempts(key TEXT PRIMARY KEY, hits INT NOT NULL, expires_at TIMESTAMPTZ NOT NULL);
`;
let initialized;
function problem(status,message){throw Object.assign(Error(message),{status});}
async function transaction(fn){
  const client=await pool.connect();
  try{await client.query('BEGIN');const result=await fn(client);await client.query('COMMIT');return result;}
  catch(error){await client.query('ROLLBACK');throw error;}
  finally{client.release();}
}
const rows=async(db,sql,...args)=>(await db.query(sql,args)).rows;
const first=async(db,sql,...args)=>(await rows(db,sql,...args))[0];
function initialize(){
  initialized??=transaction(async client=>{
    await client.query('SELECT pg_advisory_xact_lock(41751201)');
    await client.query(schema);
  }).catch(error=>{initialized=undefined;throw error;});
  return initialized;
}
function field(data,key,max=80){
  const x=data[key];if(typeof x!=='string'||x.length>max||!x.trim())problem(400,'請檢查欄位內容');
  return x.trim();
}
function password(data){
  const x=data.password;if(typeof x!=='string'||x.length<1||x.length>128)problem(400,'請檢查密碼');
  return x;
}
function recordId(x){if(!Number.isSafeInteger(x)||x<1||x>2147483647)problem(400,'資料編號無效');return x;}
function day(value,withTime=false){
  const pattern=withTime?/^\d{4}-\d\d-\d\dT\d\d:\d\d$/:/^\d{4}-\d\d-\d\d$/;
  const parsed=new Date(withTime?value+':00Z':value+'T00:00:00Z');
  if(!pattern.test(value)||!Number.isFinite(parsed.getTime())||parsed.toISOString().slice(0,value.length)!==value)problem(400,'日期或時間格式有誤');
  return value;
}
async function throttle(key,max){
  const entry=await first(pool,`
    INSERT INTO attempts(key,hits,expires_at) VALUES($1,1,NOW()+interval '5 minutes')
    ON CONFLICT(key) DO UPDATE SET hits=CASE WHEN attempts.expires_at<=NOW() THEN 1 ELSE attempts.hits+1 END,
      expires_at=CASE WHEN attempts.expires_at<=NOW() THEN EXCLUDED.expires_at ELSE attempts.expires_at END
    RETURNING hits`,sha(key));
  if(entry.hits>max)problem(429,'登入或設定嘗試過多，請稍候重試');
}
const cookie=(token,maxAge)=>'__Host-votego_session='+token+'; Path=/; HttpOnly; Secure; SameSite=Strict; Max-Age='+maxAge;
const json=(body,status=200,session)=>Response.json(body,{status,headers:{'Cache-Control':'no-store','X-Content-Type-Options':'nosniff',...(session?{'Set-Cookie':session}:{})}});
async function loginSession(userId,previous){
  if(previous)await pool.query('DELETE FROM sessions WHERE token_hash=$1',[sha(previous)]);
  const token=randomBytes(32).toString('hex');
  await pool.query("INSERT INTO sessions(token_hash,user_id,expires_at) VALUES($1,$2,NOW()+interval '8 hours')",[sha(token),userId]);
  return json({ok:true},200,cookie(token,28800));
}
async function edit(user,data){
  await transaction(async client=>{
    let item;
    const sql=(query,...args)=>first(client,query,...args);
    switch(data.action){
      case 'register':{
        const team=field(data,'team',12);
        if(!teams.includes(team))problem(400,'請選擇組別');
        item=await sql('INSERT INTO volunteers(name,team) VALUES($1,$2) RETURNING id',field(data,'name',40),team);break;
      }
      case 'review':{
        if(!['approved','rejected'].includes(data.status))problem(400,'審核結果有誤');
        item=await sql("UPDATE volunteers SET status=$1 WHERE id=$2 AND status='pending' RETURNING id",data.status,recordId(data.id));
        if(!item)problem(409,'此申請已審核或不存在');break;
      }
      case 'event':{
        const starts=day(field(data,'starts',16),true),ends=day(field(data,'ends',16),true);
        if(starts>=ends)problem(400,'結束時間必須晚於開始時間');
        item=await sql('INSERT INTO events(name,place,starts,ends) VALUES($1,$2,$3,$4) RETURNING id',field(data,'name'),field(data,'place'),starts,ends);break;
      }
      case 'shift':{
        const event=await sql('SELECT * FROM events WHERE id=$1',recordId(data.event));
        const person=await sql('SELECT * FROM volunteers WHERE id=$1 FOR UPDATE',recordId(data.volunteer));
        if(!event||person?.status!=='approved')problem(400,'請選擇活動及已核准志工');
        if(await sql('SELECT s.id FROM shifts s JOIN events e ON e.id=s.event_id WHERE s.volunteer_id=$1 AND e.starts<$2 AND e.ends>$3',person.id,event.ends,event.starts))problem(409,'此志工已有重疊班次');
        item=await sql('INSERT INTO shifts(event_id,volunteer_id) VALUES($1,$2) RETURNING id',event.id,person.id);break;
      }
      case 'task':item=await sql('INSERT INTO tasks(name,due) VALUES($1,$2) RETURNING id',field(data,'name'),day(field(data,'due',10)));break;
      case 'toggle':
        item=await sql('UPDATE tasks SET done=$1 WHERE id=$2 RETURNING id',data.done===true?1:0,recordId(data.id));
        if(!item)problem(404,'找不到任務');break;
      case 'supply':
        if(user.role!=='admin')problem(403,'只有管理員可調整庫存');
        if(!Number.isSafeInteger(data.quantity)||data.quantity<0||data.quantity>100000)problem(400,'請輸入有效庫存數量');
        item=await sql('INSERT INTO supplies(name,quantity) VALUES($1,$2) ON CONFLICT(name) DO UPDATE SET quantity=EXCLUDED.quantity RETURNING id',field(data,'name'),data.quantity);break;
      default:problem(400,'操作無效');
    }
    await client.query('INSERT INTO audit(actor_id,action,entity_id) VALUES($1,$2,$3)',[user.id,data.action,item.id]);
  });
}
async function workspace(user){
  const manager=user.role!=='volunteer';
  const [volunteers,events,shifts,tasks,supplies,audit]=await Promise.all([
    manager?rows(pool,'SELECT id,name,team,status FROM volunteers ORDER BY id DESC'):rows(pool,'SELECT id,name,team,status FROM volunteers WHERE user_id=$1',user.id),
    manager?rows(pool,'SELECT * FROM events ORDER BY starts'):rows(pool,'SELECT DISTINCT e.* FROM events e JOIN shifts s ON s.event_id=e.id JOIN volunteers v ON v.id=s.volunteer_id WHERE v.user_id=$1 ORDER BY e.starts',user.id),
    manager?rows(pool,'SELECT * FROM shifts'):rows(pool,'SELECT s.* FROM shifts s JOIN volunteers v ON v.id=s.volunteer_id WHERE v.user_id=$1',user.id),
    manager?rows(pool,'SELECT * FROM tasks ORDER BY due'):[],
    manager?rows(pool,'SELECT * FROM supplies ORDER BY name'):[],
    user.role==='admin'?rows(pool,'SELECT a.action,a.entity_id,a.created_at,u.name AS actor FROM audit a JOIN users u ON u.id=a.actor_id ORDER BY a.id DESC LIMIT 30'):[]
  ]);
  return {volunteers,events,shifts,tasks,supplies,audit};
}
export default {
 async fetch(request){
  try{
    if(!pool)problem(503,'尚未連接工作區資料庫');
    await initialize();
    const op=new URL(request.url).searchParams.get('op');
    const token=(request.headers.get('cookie')??'').match(/(?:^|;\s*)__Host-votego_session=([a-f0-9]{64})(?:;|$)/)?.[1];
    const user=token?await first(pool,'SELECT u.id,u.name,u.role FROM sessions s JOIN users u ON u.id=s.user_id WHERE token_hash=$1 AND expires_at>NOW()',sha(token)):null;
    if(request.method==='GET'){
      if(op==='session')return json({user:user??null,demo:false,teams,setupNeeded:!!process.env.VOTEGO_SETUP_CODE&&!await first(pool,'SELECT id FROM users LIMIT 1')});
      if(op==='data'){if(!user)problem(401,'請先登入');return json(await workspace(user));}
      problem(404,'找不到頁面');
    }
    if(request.method!=='POST')problem(405,'不支援此操作');
    if(request.headers.get('x-votego-request')!=='1'||!request.headers.get('content-type')?.startsWith('application/json'))problem(403,'無法驗證這次操作');
    const raw=await request.text();
    if(raw.length>12000)problem(413,'資料過長');
    let data;
    try{data=JSON.parse(raw);}catch{problem(400,'資料格式有誤');}
    if(!data||Array.isArray(data)||typeof data!=='object')problem(400,'資料格式有誤');
    const ip=request.headers.get('x-vercel-forwarded-for')?.split(',')[0]||'unknown';
    if(op==='setup'){
      const code=process.env.VOTEGO_SETUP_CODE;
      if(!code||await first(pool,'SELECT id FROM users LIMIT 1'))problem(404,'初始設定已關閉');
      await throttle('setup:'+ip,8);
      if(!equal(field(data,'code',128),code))problem(403,'設定碼有誤');
      const username=field(data,'username',32).toLowerCase(), name=field(data,'name',40), secret=password(data);
      if(!/^[a-z0-9][a-z0-9._-]{2,31}$/.test(username))problem(400,'帳號須為 3 至 32 個英數、點、底線或連字號');
      if(secret.length<12)problem(400,'密碼至少須有 12 個字元');
      const salt=randomBytes(16).toString('hex'), digest=(await derive(secret,salt,64)).toString('hex');
      const admin=await transaction(async client=>{
        await client.query('SELECT pg_advisory_xact_lock(41751202)');
        if(await first(client,'SELECT id FROM users LIMIT 1'))problem(409,'初始設定已完成');
        return first(client,"INSERT INTO users(username,name,role,salt,password_hash) VALUES($1,$2,'admin',$3,$4) RETURNING id",username,name,salt,digest);
      });
      return loginSession(admin.id,token);
    }
    if(op==='login'){
      const username=field(data,'username',32).toLowerCase(), secret=password(data);
      await throttle('login:'+ip,20);
      const row=await first(pool,'SELECT id,salt,password_hash FROM users WHERE username=$1',username);
      const digest=await derive(secret,row?.salt??'not-a-real-user',64);
      if(!row||!timingSafeEqual(digest,Buffer.from(row.password_hash,'hex')))problem(401,'帳號或密碼有誤');
      await pool.query('DELETE FROM attempts WHERE key=$1',[sha('login:'+ip)]);
      await pool.query('DELETE FROM sessions WHERE expires_at<=NOW()');
      return loginSession(row.id,token);
    }
    if(op==='logout'){
      if(token)await pool.query('DELETE FROM sessions WHERE token_hash=$1',[sha(token)]);
      return json({ok:true},200,cookie('',0));
    }
    if(!user)problem(401,'請先登入');
    if(op!=='action')problem(404,'找不到頁面');
    if(user.role==='volunteer')problem(403,'此帳號無法執行這項操作');
    await edit(user,data);
    return json({ok:true});
  }catch(error){
    if(!error.status)console.error('VoteGo workspace request failed:',error.code??error.name);
    return json({error:error.status?error.message:'系統暫時無法處理'},error.status??500);
  }
 }
};
